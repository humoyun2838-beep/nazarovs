function fold(text: string) {
  return String(text || "")
    .replace(/[\u2018\u2019\u02BB\u02BC\u02C8`´ʻʼ]/g, "'")
    .replace(/oʻ/g, "o'")
    .replace(/Oʻ/g, "O'")
    .replace(/gʻ/g, "g'")
    .replace(/Gʻ/g, "G'");
}

const SORTED = [...PAIRS]
  .flatMap(([from, to]) => {
    const folded = fold(from).toLowerCase();
    const stripped = folded.replace(/'/g, "");
    const keys = stripped === folded ? [folded] : [folded, stripped];
    return keys.filter((key) => key.length > 1).map((key) => [key, to] as [string, string]);
  })
  .sort((a, b) => b[0].length - a[0].length);

function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function applyCase(sample: string, replacement: string) {
  const first = sample.charAt(0);
  if (first && first === first.toLocaleUpperCase("uz") && first !== first.toLocaleLowerCase("uz")) {
    return replacement.charAt(0).toLocaleUpperCase("kaa") + replacement.slice(1);
  }
  return replacement;
}

export function translateKaa(text: string) {
  if (!text) return text;
  let out = fold(text);
  for (const [from, to] of SORTED) {
    const re = new RegExp(
      `(?<![\\p{L}\\p{N}])${escapeRegExp(from)}(?![\\p{L}\\p{N}])`,
      "giu",
    );
    out = out.replace(re, (match) => applyCase(match, to));
  }
  out = out.replace(/(\d+)\s+ta\b/gi, "$1 dana");
  out = out.replace(/O'/g, "Ó").replace(/o'/g, "ó");
  out = out.replace(/G'/g, "Ǵ").replace(/g'/g, "ǵ");
  return out;
}
